// Lit and unlit dot centres for a string, in dot units (one column or row = 1); unknown characters are skipped.
export function dotLayout(text) {
  const lit = [], unlit = [];
  let x = 0;
  for (const ch of String(text)) {
    const glyph = GLYPHS[ch];
    if (!glyph) continue;
    glyph.forEach((row, y) => [...row].forEach((cell, c) => (cell === '#' ? lit : unlit).push([x + c, y])));
    x += glyph[0].length + 1;
  }
  return { lit, unlit, columns: Math.max(0, x - 1), rows: 7 };
}
